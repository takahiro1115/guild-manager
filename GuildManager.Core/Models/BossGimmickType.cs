namespace GuildManager.Core.Models
{
    /// <summary>
    /// 階層ボスのギミック種別（→ ダンジョン攻略システム）。
    ///
    /// 階層ボス個体が持つ「対策の要否」。対策ロール・対策ステータス・対策アイテム
    /// （→ ConsumableCatalog。ギミック4種と1対1で対応する）のいずれかを満たしているかの
    /// 離散判定で、未対策なら被害が跳ね上がる。
    ///
    /// 設計メモ：旧・通常クエストの環境ギミック（`EnvironmentTag`。「場」に付く属性を
    /// ステータス合算と携行品で3段階に緩和し、係数として連続的に効かせる別体系）とは
    /// 独立した仕組みとして新規に設けた（ユーザー決定）。旧体系は評価器ごと撤去済み
    /// （→ 03 §0.12・§0.13）のため、現存するギミックはこの1系統のみ。
    /// </summary>
    public enum BossGimmickType
    {
        /// <summary>猛毒：継続ダメージ。MND（状態異常耐性）または解毒アイテムで対策する。</summary>
        Poison,

        /// <summary>重装甲：物理が通りにくい。STR（装甲貫通）または魔法火力で対策する。</summary>
        HeavyArmor,

        /// <summary>飛行：地上からの攻撃が届かない。DEX（遠距離命中）等で対策する。</summary>
        Flying,

        /// <summary>即死級攻撃：対策していないと一撃で戦闘不能域まで持っていかれる。</summary>
        InstantKill,
    }
}
